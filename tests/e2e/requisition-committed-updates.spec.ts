for(const language of ["en","th"] as const)test("committed priority stays visible while reconciliation is delayed "+language,async({page})=>{
 await page.setViewportSize(language==="th"?{width:390,height:844}:{width:1440,height:900});
 const mock=await installMockSupabase(page,{language});
 await page.addInitScript(()=>{(window as unknown as {__recruitmentMeasureReads:boolean}).__recruitmentMeasureReads=true;(window as unknown as {__requisitionTimings:unknown[]}).__requisitionTimings=[];window.addEventListener("recruitment:requisition-action-timing",event=>(window as unknown as {__requisitionTimings:unknown[]}).__requisitionTimings.push((event as CustomEvent).detail));});
 let saved=false;let release!:()=>void;const gate=new Promise<void>(resolve=>release=resolve);
 await page.route("**/rest/v1/requisitions*",async route=>{if(saved)await gate;await route.fallback();});
 page.on("response",response=>{if(response.url().endsWith("/rpc/app_requisition_action_v1")&&response.ok())saved=true;});
 await page.goto("/requisitions?lang="+language+"&detailType=requisition&detailId=REQ-HQ-1");
 await expectWorkspaceReady(page);
 const drawer=page.getByRole("dialog",{name:"Engineer (L4)"});
 const mark=language==="th"?"ทำเครื่องหมายคำขอเร่งด่วน":"Mark as priority";
 const remove=language==="th"?"ยกเลิกเครื่องหมายคำขอเร่งด่วน":"Remove priority";
 const before=mock.rpcCalls.filter(call=>call.endpoint==="app_home_welcome_summary_v1").length;
 await drawer.getByRole("button",{name:mark,exact:true}).click();
 await expect(drawer.locator('button[aria-pressed="true"]')).toBeVisible();
 await expect(drawer).toContainText("REQ-HQ-1");
 expect(mock.rpcCalls.filter(call=>call.endpoint==="app_requisition_action_v1")).toHaveLength(1);
 await expect.poll(()=>page.evaluate(()=>(window as unknown as {__requisitionTimings:{phase:string;durationMs:number}[]}).__requisitionTimings.find(row=>row.phase==="response-to-display")?.durationMs??Infinity)).toBeLessThan(100);
 expect(mock.rpcCalls.filter(call=>call.endpoint==="app_home_welcome_summary_v1")).toHaveLength(before);
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await test.info().attach("requisition-action-timings",{body:JSON.stringify(await page.evaluate(()=>(window as unknown as {__requisitionTimings:unknown[]}).__requisitionTimings)),contentType:"application/json"});
 release();
});
